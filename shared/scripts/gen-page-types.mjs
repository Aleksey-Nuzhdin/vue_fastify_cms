// @ts-check
/**
 * AUTO-GENERATOR for shared/types/form/pages/index.ts
 *
 * Scans the pages dir for `*.types.shared.ts` modules and emits a barrel that
 * re-exports each as a namespace: `export * as <Ns> from './<file>'`.
 * The namespace name is derived from the file name up to the first dot
 * (`login.pageData.types.shared.ts` -> `Login`, `reportCreate.types.shared.ts` -> `ReportCreate`).
 *
 * Usage:
 *   node shared/scripts/gen-page-types.mjs           # generate once
 *   node shared/scripts/gen-page-types.mjs --watch   # regenerate on changes
 */
import { readdirSync, readFileSync, writeFileSync, watch } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const PAGES_DIR = join(dirname(fileURLToPath(import.meta.url)), '..', 'types', 'form', 'pages')
const OUT_FILE = join(PAGES_DIR, 'index.ts')
const OUT_NAME = 'index.ts'
const SUFFIX = '.types.shared.ts'

const HEADER =
  '// AUTO-GENERATED by shared/scripts/gen-page-types.mjs — DO NOT EDIT.\n' +
  '// Run `node shared/scripts/gen-page-types.mjs` after adding/renaming a *.types.shared.ts file\n' +
  '// (or run it with --watch). Each module is re-exported as a namespace.\n\n'

/** @param {string} file */
const toNamespace = (file) => {
  const base = file.split('.')[0]
  return base.charAt(0).toUpperCase() + base.slice(1)
}

/** @param {string} file */
const isPageModule = (file) => file.endsWith(SUFFIX) && file !== OUT_NAME

function build() {
  const files = readdirSync(PAGES_DIR).filter(isPageModule).sort()
  // Extensionless specifier: `export * as` is a real re-export (not `import type`),
  // so a `.ts` extension would need `allowImportingTsExtensions` (off on the server).
  // Both client and server use `moduleResolution: Bundler`, which resolves extensionless.
  const lines = files.map((f) => `export * as ${toNamespace(f)} from './${f.slice(0, -3)}'`)
  return { content: HEADER + lines.join('\n') + '\n', files, lines }
}

function generate() {
  const { content, files, lines } = build()
  let current = ''
  try {
    current = readFileSync(OUT_FILE, 'utf8')
  } catch {
    /* no existing file */
  }
  if (current === content) {
    console.log(`[gen-page-types] up to date (${files.length} namespaces)`)
    return
  }
  writeFileSync(OUT_FILE, content)
  console.log(
    `[gen-page-types] wrote ${OUT_NAME} (${files.length} namespaces):\n` +
      lines.map((l) => '  ' + l).join('\n'),
  )
}

generate()

if (process.argv.includes('--watch')) {
  console.log('[gen-page-types] watching', PAGES_DIR)
  let timer = null
  watch(PAGES_DIR, (_event, filename) => {
    // Ignore writes to the generated file itself to avoid a regen loop.
    if (!filename || !isPageModule(filename)) return
    clearTimeout(timer)
    timer = setTimeout(generate, 100)
  })
}
